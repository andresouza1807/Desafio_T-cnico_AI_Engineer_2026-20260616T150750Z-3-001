def _rows(index: PolicyIndex) -> list[tuple[Any, ...]]:
    return [
        (s.section_id, s.level, s.parent_id, s.title, s.heading_page, s.lines)
        for s in index.sections
    ]


def _section(index: PolicyIndex, section_id: str) -> IndexedSection:
    matches = [s for s in index.sections if s.section_id == section_id]
    assert len(matches) == 1
    return matches[0]


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _prepare_error(source: Path, target: Path) -> PolicyPreparationError:
    with pytest.raises(PolicyPreparationError) as caught:
        prepare_policy_index(source, target)
    return caught.value


