def _index_size(policy_kit: Any, directory: Path) -> int:
    """Size in bytes of the real index of MINI, measured on a file prepared with the
    default limit (the filesystem measures it; no production function computes it)."""
    folder = directory / "reference"
    folder.mkdir()
    source = policy_kit.write(folder)  # same base name, so the same JSON length
    reference = folder / "index.json"
    prepare_policy_index(source, reference)
    size = reference.stat().st_size
    reference.unlink()
    source.unlink()
    folder.rmdir()
    return size


def _oversize_error(source: Path, target: Path) -> PolicyIndexUnavailableError:
    with pytest.raises(PolicyIndexUnavailableError) as caught:
        prepare_policy_index(source, target)
    error = caught.value
    assert error.code == "index_invalid"
    assert error.file_name == "index.json"
    assert error.__cause__ is None
    assert error.__suppress_context__ is True
    return error


