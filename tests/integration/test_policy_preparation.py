    for error in errors:
        assert _forbidden(error, tmp_path) == []
        assert error.__cause__ is None
        assert error.__suppress_context__ is True
        assert error.args == (str(error),)
        assert error.file_name in {"manual-sintetico.pdf", "index.json"}


