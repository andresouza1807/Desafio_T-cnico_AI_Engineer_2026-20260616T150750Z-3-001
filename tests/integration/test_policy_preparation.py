def test_p04_no_front_matter_when_no_line_precedes_first_heading(
    policy_kit: Any, tmp_path: Path
) -> None:
    # Added check (see report): page 1 removed, every numbered section kept, so the
    # absence of front_matter is observable on a successful extraction.
    def drop_cover(layout: dict[str, Any]) -> None:
        del layout["pages"][0]

        def shift(entries: list[dict[str, Any]]) -> None:
            for entry in entries:
                entry["page"] -= 1
                shift(entry["children"])

        shift(layout["outline"])

    index = extract_policy_index(policy_kit.write(tmp_path, edit=drop_cover))

    assert tuple(s.section_id for s in index.sections) == SECTION_IDS[1:]
    assert index.source.page_count == 4
    assert _section(index, "4.1").pages == (2, 3)


