    second = tmp_path / "second.json"

    prepare_policy_index(source, first)
    prepare_policy_index(source, second)

    assert first.read_bytes() == second.read_bytes()
    keys = set(_keys(json.loads(first.read_bytes())))
    for key in keys:
        lowered = key.lower()
