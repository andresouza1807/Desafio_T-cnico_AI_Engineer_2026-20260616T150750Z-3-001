    run(source, source)
    with monkeypatch.context() as patch:
        patch.setattr(pi.os, "replace", lambda *_: (_ for _ in ()).throw(OSError(str(root))))
        run(source, folder / "index.json")

    codes = sorted({error.code for error in errors})
