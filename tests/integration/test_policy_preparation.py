def _write_variant(policy_kit: Any, directory: Path, variant: str) -> Path:
    raw = {"raw_empty": b"", "raw_text": b"not a pdf"}
    path = directory / "manual-sintetico.pdf"
    if variant in raw:
        path.write_bytes(raw[variant])
    elif variant == "raw_truncated":
        path.write_bytes(policy_kit.build()[:400])
    else:
        policy_kit.write(directory, edit=variant)
    return path


